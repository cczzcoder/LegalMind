"""提问范围与输出边界（设计 §20.2、§9.3 第三层）。

**两件设计明确要求、此前没做的事**：

1. **每个正式输出都要带「不构成法律意见」声明与知识范围说明**（§20.2，需求第 262 行）。这不是
   客套话——它是「无资质提供法律服务」这条风险的**控制措施本身**（§20.1 的风险映射表）。
   所以它做成 `Answer` 的一个**必填字段**而不是调用方的自觉：结构上就发布不出一份不带声明的结论。
2. **高风险个性化判断转人工**（§9.3 第三层）。实测（2026-10-06）问「我是名特困人员，我能否领到
   社会救助？」，模型答得**引用正确、内容也对**，但最后加了一句「因此，作为特困人员，可以领取
   社会救助」——把「法律怎么规定」变成了「你能领」。这正是 §20.2「不提供法律服务、不替代执业律师
   判断」要拦的那一步，而且它还悄悄跳过了「特困人员须经认定程序」这个前提。

**识别方式与它的边界**：这里用**规则匹配**（第一人称 + 资格/权利义务判断词），不是语义理解。
所以它**会漏**（换个说法就绕过去）也**会误报**。因此它的后果被刻意定得很轻——**不给个人结论、
把条文交回人工**，而不是「判定用户不能问」。**宁可多转一次人工，也不要多给一句个人结论。**
"""

import re

#: §20.2 要求的输出声明。**每个正式输出都必须带**，所以它是 `Answer` 的字段而不是提示词的一部分。
DISCLAIMER = (
    "本回答是法律信息的整理，不构成法律意见，不能替代执业律师的判断；"
    "依据仅限本次检索到的条文（见「依据」），效力状态与最新文本请以官方发布为准。"
)

#: 命中个性化提问时的说明——**不生成个人结论**，把条文与下一步交回提问者。
SCOPE_NOTICE = (
    "这个问题问的是提问者本人的情形（{reason}）。本工具是法律信息辅助工具，"
    "不对个人情形下结论，因此**不生成个人结论**。以下是检索到的相关条文，请自行核对；"
    "个人是否符合条件须经法定认定程序，如需就本人情形获得结论，请转人工审核或咨询执业律师。"
)

#: 第一人称：提问者本人（或本人所在单位）的视角。
_FIRST_PERSON = ("我", "本人", "自己", "咱", "我方")

#: 对「本人资格 / 权利义务」下判断的说法。**刻意收窄**：只收资格与权利义务类，
#: 不收「怎么办」「是什么」这类纯信息问法——否则「我想知道社会救助分几类」会被误判。
_JUDGEMENT = (
    "能否",
    "能不能",
    "可不可以",
    "是否可以",
    "有没有权",
    "有没有资格",
    "该不该",
    "要不要",
    "可以领",
    "能领",
    "可以享受",
    "能享受",
    "可以申请",
    "能申请",
    "算不算",
    "够不够",
    "是否符合",
    "有没有权享受",
    "资格",
)

_WS = re.compile(r"[\s\u3000]+")


def detect_personal_scope(question: str) -> str | None:
    """问题是否在问「提问者本人能不能 / 该不该」——是则返回命中的理由，否则 None。"""
    text = _WS.sub("", question or "")
    person = next((word for word in _FIRST_PERSON if word in text), None)
    if person is None:
        return None
    judgement = next((word for word in _JUDGEMENT if word in text), None)
    if judgement is None:
        return None
    return f"命中「{person}」+「{judgement}」"


def scope_notice(question: str) -> str | None:
    """个性化提问时给出边界说明；否则 None。"""
    reason = detect_personal_scope(question)
    return None if reason is None else SCOPE_NOTICE.format(reason=reason)
